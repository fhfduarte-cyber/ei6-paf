// Extracts the datasets that are embedded in the legacy single-file calculator into JSON seed files.
// usage: node tools/extract_datasets.mjs <legacy index.html> <out dir>
import fs from 'node:fs'; import vm from 'node:vm'; import path from 'node:path';
const [src, out] = process.argv.slice(2);
const html = fs.readFileSync(src, 'utf8');
function grab(name) {
  const i = html.indexOf(`const ${name}=`);
  if (i < 0) throw new Error('not found: ' + name);
  let j = html.indexOf('=', i) + 1, depth = 0, inStr = null, k = j;
  for (; k < html.length; k++) {
    const c = html[k];
    if (inStr) { if (c === '\\') k++; else if (c === inStr) inStr = null; continue; }
    if (c === '"' || c === "'" || c === '`') { inStr = c; continue; }
    if (c === '[' || c === '{') depth++;
    if (c === ']' || c === '}') { depth--; if (depth === 0) { k++; break; } }
  }
  return html.slice(j, k);
}
const ctx = vm.createContext({ IN: 25.4, KG_LB_: 0.45359237 });
const ev = (name) => vm.runInContext('(' + grab(name) + ')', ctx);
fs.mkdirSync(out, { recursive: true });
const r = (n) => Math.round(n * 1e9) / 1e9;
const clean = (o) => JSON.parse(JSON.stringify(o, (k, v) => typeof v === 'number' ? r(v) : v));
const sets = {
  prices_blocks: ev('PRICES'), prices_rods: ev('RODPRICES'), prices_rounds: ev('ROUNDPRICES'),
  devaluation: { source: 'Devaluation_v7.xlsx', blocks: ev('RULES'), rods: ev('ROD_V7'), rounds: ev('RND_V7') },
  parma_stock: { source: 'Parma M Aged Report.xlsx', rows: ev('DIGGER_DATA') },
};
for (const [k, v] of Object.entries(sets)) {
  fs.writeFileSync(path.join(out, k + '.json'), JSON.stringify(clean(v)));
  console.log(k, Array.isArray(v) ? v.length : Object.keys(v).join(','), fs.statSync(path.join(out, k + '.json')).size + ' bytes');
}
// SQL seed (dollar-quoted jsonb, tag cannot appear in the data)
let sql = '-- Generated by tools/extract_datasets.mjs. Re-run to refresh the seed.\n';
for (const k of Object.keys(sets)) {
  const j = fs.readFileSync(path.join(out, k + '.json'), 'utf8');
  if (j.includes('$ei6$')) throw new Error('tag clash');
  sql += `insert into public.datasets(key,data) values ('${k}', $ei6$${j}$ei6$::jsonb)\n  on conflict (key) do update set data = excluded.data;\n`;
}
fs.writeFileSync(path.join(out, '..', 'migrations', '0002_seed_datasets.sql'), sql);
